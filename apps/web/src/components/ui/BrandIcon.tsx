// ─── Component ───────────────────────────────────────────────────────────────

export default function BrandIcon({ brand, size = 32, contained = true, className = '' }: BrandIconProps) {
  const si = SI_PATHS[brand]
  const mono = MONOGRAMS[brand]

  // ── SI path icon ──
  if (si) {
    if (!contained) {
      return (
        <svg viewBox="0 0 24 24" width={size} height={size} fill={`#${si.hex}`} className={className}>
          <path d={si.path} />
        </svg>
      )
    }
    return (
      <div
        className={`flex-shrink-0 flex items-center justify-center bg-white border border-slate-200 overflow-hidden ${className}`}
        style={{ width: size, height: size }}
      >
        <svg viewBox="0 0 24 24" width={size * 0.6} height={size * 0.6} fill={`#${si.hex}`}>
          <path d={si.path} />
        </svg>
      </div>
    )
  }

  // ── Monogram icon (white bg, brand-color border + text) ──
  if (mono) {
    const isSmall = mono.text.length > 2
    const fontSize = isSmall ? size * 0.25 : size * 0.3

    if (!contained) {
      // Render as SVG so it composes cleanly inside the marquee white pill
      return (
        <svg viewBox="0 0 24 24" width={size} height={size} className={className}>
          <rect width="24" height="24" rx="3" fill="white" />
          <rect width="24" height="24" rx="3" fill="none" stroke={`#${mono.hex}`} strokeWidth="1.5" />
          <text
            x="12" y="12"
            textAnchor="middle"
            dominantBaseline="central"
            fill={`#${mono.hex}`}
            fontFamily="DM Sans, system-ui, sans-serif"
            fontSize={isSmall ? '7' : '9'}
            fontWeight="700"
            letterSpacing="-0.3"
          >
            {mono.text}
          </text>
        </svg>
      )
    }

    return (
      <div
        className={`flex-shrink-0 flex items-center justify-center bg-white overflow-hidden ${className}`}
        style={{
          width: size,
          height: size,
          border: `2px solid #${mono.hex}`,
        }}
      >
        <span
          className="font-bold leading-none select-none"
          style={{ fontSize, color: `#${mono.hex}`, letterSpacing: '-0.03em' }}
        >
          {mono.text}
        </span>
      </div>
    )
  }

  // Generic fallback
  return (
    <div
      className={`flex-shrink-0 flex items-center justify-center bg-slate-100 border border-slate-200 ${className}`}
      style={{ width: size, height: size }}
    >
      <span className="text-slate-500 font-semibold text-xs">{brand.slice(0, 2).toUpperCase()}</span>
    </div>
  )
}
